let currentLang = localStorage.getItem("kc_lang") || "en";

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("kc_lang", lang);
  document.documentElement.lang = lang === "hi" ? "hi" : lang === "mr" ? "mr" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });
}

function initI18n() {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      setLanguage(btn.getAttribute("data-lang"));
    });
  });
  setLanguage(currentLang);
}

// Expose for other scripts
window.KC = window.KC || {};
window.KC.setLanguage = setLanguage;
window.KC.currentLang = () => currentLang;
window.KC.t = (key) => (translations[currentLang] && translations[currentLang][key]) || key;
